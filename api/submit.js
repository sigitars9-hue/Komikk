// Serverless Function @ Vercel
// Membuat PR ke repo yang ditentukan ENV: GITHUB_TOKEN, GH_REPO, SUBMIT_SECRET

import { Octokit } from "@octokit/rest";

export default async function handler(req, res) {
  try {
    // --- keamanan sederhana ---
    if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed" });
    const secret = req.headers["x-submit-secret"] || req.query.secret;
    if (!secret || secret !== process.env.SUBMIT_SECRET) {
      return res.status(401).json({ error: "Unauthorized" });
    }

    const { payload } = req.body || {};
    if (!payload) return res.status(400).json({ error: "Missing payload" });

    // ENV
    const token = process.env.GITHUB_TOKEN;
    const repoFull = process.env.GH_REPO; // e.g. "gvteam/gv-comics-api"
    if (!token || !repoFull) return res.status(500).json({ error: "Missing server env" });

    const [owner, repo] = repoFull.split("/");
    const octokit = new Octokit({ auth: token });

    // 1) ambil info default branch
    const repoInfo = await octokit.repos.get({ owner, repo });
    const baseBranch = repoInfo.data.default_branch || "main";

    // 2) ambil file data.json di root (sesuaikan path kalau file-mu di subfolder)
    const dataPath = "data.json"; // <-- ubah kalau perlu, mis. "data/data.json"
    const fileResp = await octokit.repos.getContent({ owner, repo, path: dataPath, ref: baseBranch });

    if (!Array.isArray(fileResp.data) && fileResp.data.type === "file") {
      const sha = fileResp.data.sha;
      const buf = Buffer.from(fileResp.data.content, "base64");
      const text = buf.toString("utf8");

      // 3) parse & modifikasi
      let json;
      try {
        json = JSON.parse(text);
      } catch (e) {
        return res.status(500).json({ error: "Invalid JSON in data.json" });
      }

      // Aturan merge sederhana:
      // - kalau payload.series => dorong satu objek ke array json.series
      // - kalau payload.seriesBatch => array; concat ke json.series
      // - kalau payload.patch dengan path & value => set langsung
      if (!json.series) json.series = [];

      if (payload.seriesBatch && Array.isArray(payload.seriesBatch)) {
        json.series = [...json.series, ...payload.seriesBatch];
      } else if (payload.series) {
        json.series.push(payload.series);
      } else if (payload.patch && payload.patch.path) {
        // opsional: patch dengan dot-path, contoh: { path: "series[3].chapters", value: [...] }
        setByPath(json, payload.patch.path, payload.patch.value);
      } else {
        return res.status(400).json({ error: "Unsupported payload shape" });
      }

      const updatedText = JSON.stringify(json, null, 2);
      const updatedBase64 = Buffer.from(updatedText, "utf8").toString("base64");

      // 4) buat branch baru dari base
      const baseRef = await octokit.git.getRef({ owner, repo, ref: `heads/${baseBranch}` });
      const newBranch = `bot/submit-${Date.now()}`;
      await octokit.git.createRef({
        owner, repo,
        ref: `refs/heads/${newBranch}`,
        sha: baseRef.data.object.sha,
      });

      // 5) commit file ke branch baru
      await octokit.repos.createOrUpdateFileContents({
        owner, repo,
        path: dataPath,
        message: `chore(data): update via generator (${new Date().toISOString()})`,
        content: updatedBase64,
        sha,
        branch: newBranch,
      });

      // 6) buat PR
      const pr = await octokit.pulls.create({
        owner, repo,
        title: `Update data.json via generator`,
        head: newBranch,
        base: baseBranch,
        body: "Auto-generated by GVComics Generator.",
      });

      return res.status(200).json({ ok: true, prUrl: pr.data.html_url });
    }

    return res.status(404).json({ error: "data.json not found" });
  } catch (e) {
    console.error(e);
    return res.status(500).json({ error: e.message || "Server error" });
  }
}

/* util: set value by dot/array path */
function setByPath(obj, path, value) {
  const segs = path.replace(/\[(\d+)\]/g, ".$1").split(".");
  let cur = obj;
  for (let i = 0; i < segs.length - 1; i++) {
    const k = segs[i];
    if (!(k in cur) || typeof cur[k] !== "object") cur[k] = {};
    cur = cur[k];
  }
  cur[segs[segs.length - 1]] = value;
}
